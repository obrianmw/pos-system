import uuid
from decimal import Decimal

from django.conf import settings
from django.db import models

from apps.catalog.models import Product
from apps.core.models import Branch, Organization, Till, TimeStamped


class Customer(TimeStamped):
    organization = models.ForeignKey(Organization, on_delete=models.CASCADE, related_name="customers")
    name = models.CharField(max_length=200)
    phone = models.CharField(max_length=30, blank=True, db_index=True)
    email = models.EmailField(blank=True)
    tax_number = models.CharField(max_length=50, blank=True)
    credit_limit = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    loyalty_points = models.IntegerField(default=0)

    def __str__(self):
        return self.name


class TillSession(TimeStamped):
    """A cashier's shift on a till: opening float -> sales -> cash count -> variance."""

    STATUS = [("open", "Open"), ("closed", "Closed")]
    till = models.ForeignKey(Till, on_delete=models.PROTECT, related_name="sessions")
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name="till_sessions")
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="till_sessions")
    status = models.CharField(max_length=10, choices=STATUS, default="open", db_index=True)
    opening_float = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    opened_at = models.DateTimeField(auto_now_add=True)
    closed_at = models.DateTimeField(null=True, blank=True)
    closed_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, null=True, blank=True,
                                  related_name="+")
    expected_cash = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    counted_cash = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    variance = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    notes = models.TextField(blank=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["till"], condition=models.Q(status="open"),
                                               name="one_open_session_per_till")]

    def __str__(self):
        return f"{self.till} {self.opened_at:%Y-%m-%d %H:%M} ({self.status})"


class Sale(TimeStamped):
    KIND = [("sale", "Sale"), ("refund", "Refund / return")]
    STATUS = [("pending_payment", "Awaiting payment"), ("completed", "Completed"), ("voided", "Voided"),
              ("cancelled", "Cancelled")]
    organization = models.ForeignKey(Organization, on_delete=models.PROTECT, related_name="sales")
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name="sales")
    till_session = models.ForeignKey(TillSession, on_delete=models.PROTECT, related_name="sales")
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="sales")
    customer = models.ForeignKey(Customer, on_delete=models.PROTECT, null=True, blank=True)
    number = models.CharField(max_length=40, unique=True)
    # Generated by the till; makes offline sync idempotent (resending the same sale is harmless).
    client_uuid = models.UUIDField(default=uuid.uuid4, unique=True)
    kind = models.CharField(max_length=10, choices=KIND, default="sale")
    status = models.CharField(max_length=20, choices=STATUS, default="pending_payment", db_index=True)
    original_sale = models.ForeignKey("self", on_delete=models.PROTECT, null=True, blank=True,
                                      related_name="refunds")
    currency = models.CharField(max_length=3, default="MWK")
    subtotal = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    discount_total = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    tax_total = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    total = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    created_offline = models.BooleanField(default=False)
    client_created_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    # Offline sales whose override PIN or payment could not be verified on sync land here.
    needs_review = models.BooleanField(default=False, db_index=True)
    review_reason = models.TextField(blank=True)
    note = models.CharField(max_length=255, blank=True)

    class Meta:
        indexes = [models.Index(fields=["branch", "created_at"]), models.Index(fields=["branch", "status"])]

    def __str__(self):
        return self.number

    @property
    def paid_total(self):
        return sum((p.amount for p in self.payments.all() if p.status == "confirmed"), Decimal("0"))


class SaleLine(models.Model):
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="lines")
    product = models.ForeignKey(Product, on_delete=models.PROTECT)
    description = models.CharField(max_length=200)
    quantity = models.DecimalField(max_digits=14, decimal_places=3)
    list_price = models.DecimalField(max_digits=14, decimal_places=2)
    unit_price = models.DecimalField(max_digits=14, decimal_places=2, help_text="Price actually charged")
    discount_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0"))
    tax_rate = models.DecimalField(max_digits=5, decimal_places=2, default=Decimal("0"))
    tax_inclusive = models.BooleanField(default=True)
    tax_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0"))
    line_total = models.DecimalField(max_digits=16, decimal_places=2, help_text="Incl. tax, after discount")
    unit_cost = models.DecimalField(max_digits=14, decimal_places=4, default=Decimal("0"))
    original_line = models.ForeignKey("self", on_delete=models.PROTECT, null=True, blank=True,
                                      related_name="refund_lines")
    override = models.ForeignKey("OverrideApproval", on_delete=models.PROTECT, null=True, blank=True,
                                 related_name="lines")

    @property
    def net_amount(self):
        return self.line_total - self.tax_amount


class OverrideApproval(TimeStamped):
    """A supervisor's approval for something a cashier may not do alone.

    `method`:
      pin    - supervisor typed their PIN on the cashier's till
      remote - cashier raised a request; supervisor approved it from their own device
      self   - the user already holds the permission
    """

    KIND = [("price", "Price change"), ("discount", "Discount above limit"), ("void", "Void sale"),
            ("refund", "Refund / return")]
    STATUS = [("pending", "Pending"), ("approved", "Approved"), ("rejected", "Rejected"), ("used", "Used")]
    METHOD = [("pin", "PIN at till"), ("remote", "Remote approval"), ("self", "Own permission")]
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name="overrides")
    kind = models.CharField(max_length=10, choices=KIND)
    status = models.CharField(max_length=10, choices=STATUS, default="pending", db_index=True)
    method = models.CharField(max_length=10, choices=METHOD, default="remote")
    requested_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    approved_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, null=True, blank=True,
                                    related_name="+")
    product = models.ForeignKey(Product, on_delete=models.PROTECT, null=True, blank=True)
    sale = models.ForeignKey(Sale, on_delete=models.PROTECT, null=True, blank=True, related_name="overrides")
    original_value = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    new_value = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    reason = models.CharField(max_length=255)
    decided_at = models.DateTimeField(null=True, blank=True)

    def __str__(self):
        return f"{self.get_kind_display()} {self.original_value}->{self.new_value} [{self.status}]"


class Proforma(models.Model):
    """A priced quotation printed before a sale (no stock or ledger effect). Lines are a snapshot of the
    prices at the time, so a reprint shows exactly what the customer was given."""

    organization = models.ForeignKey(Organization, on_delete=models.PROTECT, related_name="proformas")
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name="proformas")
    number = models.CharField(max_length=30, unique=True)
    customer_name = models.CharField(max_length=200, blank=True)
    customer_phone = models.CharField(max_length=30, blank=True)
    note = models.CharField(max_length=255, blank=True)
    lines = models.JSONField(default=list)
    subtotal = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    tax_total = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    total = models.DecimalField(max_digits=16, decimal_places=2, default=Decimal("0"))
    valid_until = models.DateField()
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return self.number
